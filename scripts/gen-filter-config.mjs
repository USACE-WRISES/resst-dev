// Generates src/config/filters.generated.ts from the filter definitions
// captured out of the Experience Builder published config
// (RESST-migration/07-assessment/filter-config-extracted.json).
//
// Faithful port of the current app's three filter widgets:
//   - item order and curated option order are preserved;
//   - items whose clause carries a predefined value list become `options`;
//   - items without one (Site Name, the covered_topics flags) are `dynamic`
//     — the UI computes distinct values from the data at runtime, which is
//     how their pickers behaved in Experience Builder;
//   - operator IS_ANY_OF → exact value match; CONTAINS → substring match
//     (both case-insensitive, mirroring ArcGIS hosted-layer semantics);
//   - lit_ prefixes and the two truncated Survey123 field names are mapped to
//     the repo CSV schema;
//   - the dead "Water Injection Dreding" option is spelled correctly
//     (documented deliberate difference — data always said "Dredging").
//
//   node scripts/gen-filter-config.mjs

import { readFile, writeFile } from "node:fs/promises";

const cfg = JSON.parse(await readFile("RESST-migration/07-assessment/filter-config-extracted.json", "utf8"));

const WIDGET_TO_DOMAIN = {
  widget_171: "sites",
  widget_180: "siteLit",
  widget_177: "generalLit",
};

const renameField = (field, domain) => {
  let f = field;
  if (domain === "siteLit") f = f.replace(/^lit_/, "");
  f = f
    .replace("covered_topics_ecological_syste", "covered_topics_ecological_systems")
    .replace("covered_topics_future_condition", "covered_topics_future_conditions");
  return f;
};

const fixValue = (v) => v.replace("Water Injection Dreding", "Water Injection Dredging");

const defs = [];
for (const [wid, domain] of Object.entries(WIDGET_TO_DOMAIN)) {
  const w = cfg[wid];
  for (const item of w.items) {
    const valueClause = item.clauses.find((c) => c.operator === "STRING_OPERATOR_CONTAINS" || c.operator === "STRING_OPERATOR_IS_ANY_OF");
    if (!valueClause) continue;
    const field = renameField(valueClause.field, domain);
    const match = valueClause.operator === "STRING_OPERATOR_IS_ANY_OF" ? "exact" : "contains";
    const key = `${domain}.${field}`;
    const def = { key, domain, field, label: item.name, match };
    if (Array.isArray(valueClause.values) && valueClause.values.length) def.options = valueClause.values.map(fixValue);
    else def.dynamic = true;
    defs.push(def);
  }
}

const banner = `// GENERATED by scripts/gen-filter-config.mjs — do not edit by hand.
// Source: the Experience Builder filter widgets captured in
// RESST-migration/07-assessment/filter-config-extracted.json.
// Regenerate with: node scripts/gen-filter-config.mjs
`;
const body = `${banner}
import type { FilterDef } from "../filters/engine";

export const FILTER_DEFS: FilterDef[] = ${JSON.stringify(defs, null, 2)};
`;
await writeFile("src/config/filters.generated.ts", body, "utf8");
const byDomain = defs.reduce((m, d) => ((m[d.domain] = (m[d.domain] ?? 0) + 1), m), {});
console.log(`Wrote src/config/filters.generated.ts — ${defs.length} filter items`, byDomain);
